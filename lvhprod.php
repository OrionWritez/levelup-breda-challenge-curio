        const productSearch = document.getElementById("product-search-input");
        const productCatalog = document.getElementById("product-catalog");
        const productCards = Array.from(productCatalog.querySelectorAll(".product-card"));
        const productSearchStatus = document.getElementById("product-search-status");
        const categoryFilters = document.getElementById("product-category-filters");
        const categories = [
            {
                title: "Monitoren",
                matches: (name) => name.includes("monitor")
            },
            {
                title: "Pc's & laptops",
                matches: (name) => name.includes("laptop") || name.includes("gaming pc")
            },
            {
                title: "Toetsenborden & muizen",
                matches: (name) => name.includes("toetsenbord") || name.includes("muis")
            },
            {
                title: "Headsets & audio",
                matches: (name) => name.includes("headset") || name.includes("microfoon")
            },
            {
                title: "PC-upgrades",
                matches: (name) => /ssd|geheugen|voeding|behuizing|waterkoeling|fans|adapter/.test(name)
            },
            {
                title: "Setup & accessoires",
                matches: () => true
            }
        ].map((category) => ({
            ...category,
            section: document.createElement("section"),
            grid: document.createElement("div")
        }));

        categories.forEach((category) => {
            category.section.className = "product-category";
            category.section.setAttribute("aria-label", category.title);

            const heading = document.createElement("h2");
            heading.textContent = category.title;
            category.grid.className = "products";
            category.section.append(heading, category.grid);
        });

        productCards.forEach((card) => {
            const productName = card.querySelector("h3").textContent.toLocaleLowerCase("nl");
            const category = categories.find((item) => item.matches(productName));
            category.grid.append(card);
        });

        productCatalog.replaceChildren(...categories
            .filter((category) => category.grid.childElementCount > 0)
            .map((category) => category.section));

        const productCategories = Array.from(productCatalog.querySelectorAll(".product-category"));

        let selectedCategory = null;
        const categoryButtons = [];

        const addCategoryButton = (label, category) => {
            const button = document.createElement("button");
            button.type = "button";
            button.className = "product-category-button";
            button.textContent = label;
            button.setAttribute("aria-pressed", category === selectedCategory ? "true" : "false");
            button.addEventListener("click", () => {
                selectedCategory = category;
                categoryButtons.forEach((item) => {
                    item.button.setAttribute(
                        "aria-pressed",
                        item.category === selectedCategory ? "true" : "false"
                    );
                });
                updateProducts();
            });
            categoryFilters.append(button);
            categoryButtons.push({ button, category });
        };

        addCategoryButton("Alle producten", null);
        categories
            .filter((category) => category.grid.childElementCount > 0)
            .forEach((category) => addCategoryButton(category.title, category));

        const updateProducts = () => {
            const searchTerm = productSearch.value.trim().toLocaleLowerCase("nl");
            let visibleProducts = 0;

            productCategories.forEach((category) => {
                const categoryData = categories.find((item) => item.section === category);
                const categorySelected = selectedCategory === null || selectedCategory === categoryData;

                Array.from(category.querySelectorAll(".product-card")).forEach((card) => {
                    const productName = card.querySelector("h3").textContent.toLocaleLowerCase("nl");
                    const matches = categorySelected && productName.includes(searchTerm);
                    card.hidden = !matches;

                    if (matches) visibleProducts += 1;
                });

                category.hidden = !categorySelected
                    || !Array.from(category.querySelectorAll(".product-card")).some((card) => !card.hidden);
            });

            if (visibleProducts === 0) {
                productSearchStatus.textContent = "Geen producten gevonden.";
            } else if (searchTerm || selectedCategory !== null) {
                productSearchStatus.textContent = `${visibleProducts} ${visibleProducts === 1 ? "product" : "producten"} gevonden.`;
            } else {
                productSearchStatus.textContent = `${visibleProducts} producten beschikbaar.`;
            }
        };

        productSearch.addEventListener("input", updateProducts);
        updateProducts();

        const newsletterDialog = document.getElementById("newsletter-dialog");
        const openNewsletter = document.getElementById("open-newsletter");
        const closeNewsletter = document.getElementById("close-newsletter");
        const newsletterForm = document.getElementById("newsletter-form");
        const newsletterStatus = document.getElementById("newsletter-status");

        openNewsletter.addEventListener("click", () => newsletterDialog.showModal());
        closeNewsletter.addEventListener("click", () => newsletterDialog.close());

        newsletterDialog.addEventListener("click", (event) => {
            if (event.target === newsletterDialog) newsletterDialog.close();
        });

        newsletterForm.addEventListener("submit", (event) => {
            event.preventDefault();
            const name = document.getElementById("newsletter-name").value.trim();
            newsletterStatus.textContent = `Bedankt, ${name}! Je staat nu ingeschreven voor ons nieuws.`;
            newsletterForm.reset();
        });
    </script>

